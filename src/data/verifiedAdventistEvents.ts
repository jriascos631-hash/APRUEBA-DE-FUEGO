/**
 * Filtra eventos que siguen vigentes (próximos o en curso) a partir de la fecha actual.
 */
export function getUpcomingAndOngoingEvents(events: EventItem[], currentDate: Date = new Date('2026-10-23T15:00:00Z')): EventItem[] {
  return events.filter(e => {
    if (e.status === 'proximo' || e.status === 'en_curso' || e.status === 'por_confirmar') {
      return true;
    }
    if (e.endDate) {
      const end = new Date(e.endDate);
      return !isNaN(end.getTime()) && end >= currentDate;
    }
    return false;
  });
}

/**
 * Obtiene eventos que ya han finalizado y forman parte del historial verificado.
 */
export function getPastEvents(events: EventItem[], currentDate: Date = new Date('2026-10-23T15:00:00Z')): EventItem[] {
  return events.filter(e => {
    if (e.status === 'finalizado') {
      return true;
    }
    if (e.endDate) {
      const end = new Date(e.endDate);
      return !isNaN(end.getTime()) && end < currentDate;
    }
    return false;
  });
}
